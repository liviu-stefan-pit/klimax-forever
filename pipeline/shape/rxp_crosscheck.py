"""Cross-check our band packs against the quest ids RXPGuides' Forever Horde guides use.

Input: ``data/raw/game/rxp_quest_ids.json`` (ids and step order only, see
:mod:`pipeline.extract.rxp_guides`), our band packs, ``unassigned.json`` and ``data/raw``.
Output: ``docs/reports/rxp_crosscheck.md``. Only ids, names from our own DB, flags and counts go
into the report; nothing of RXP's text. Every discrepancy is a question about our shaping rules.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from pipeline.shape.context import ShapeContext, race_available
from pipeline.shape.data import RawData, load_raw
from pipeline.shape.factions import get_faction

WINDOW = 2  # a quest belongs to a band when questLevel is in [lo - WINDOW, hi + WINDOW]
RISKY_FLAGS = ("elite", "group", "dungeon")
DROPPABLE_FLAGS = ("breadcrumb", "chainHead")
MAX_IDS_SHOWN = 40


def load_packs(bands_dir: Path) -> list[dict[str, Any]]:
    packs = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(bands_dir.glob("*.json"))]
    packs.sort(key=lambda p: (p["band"][0], p["band"][1], p["id"]))
    return packs


def rxp_usage(rxp: dict[str, Any]) -> dict[int, dict[str, Any]]:
    """quest id -> {branches, actions, firstStep, conditional} over all RXP Horde guides."""
    usage: dict[int, dict[str, Any]] = {}
    for _name, entry in sorted(rxp["files"].items()):
        for guide in entry["guides"]:
            for _step, action, qid, cond in guide["steps"]:
                row = usage.setdefault(
                    qid, {"branches": set(), "actions": set(), "conditional": True}
                )
                row["branches"].add(entry["branch"])
                row["actions"].add(action)
                row["conditional"] = row["conditional"] and cond
    return usage


def _reason(ctx: ShapeContext, raw: RawData, qid: int, unassigned: set[int]) -> str:
    quest = raw.quests.get(qid)
    if quest is None:
        return "not in the DB"
    if quest.get("placeholder"):
        return "placeholder record"
    if not race_available(int(quest.get("requiredRaces", 0)), ctx.cfg):
        return "not available to Horde (race/faction bits)"
    if qid not in ctx.quests:
        return "no usable starter"
    if qid in unassigned:
        return "no start branch (unassigned)"
    info = ctx.quests[qid]
    return f"kept by filters, in no pack (level {info.level})"


def _name(raw: RawData, qid: int) -> str:
    quest = raw.quests.get(qid)
    return str(quest.get("name")) if quest and quest.get("name") else "?"


def _ids(
    raw: RawData, ids: list[int], where: dict[int, list[str]] | None = None
) -> str:
    def one(q: int) -> str:
        text = f"{q} {_name(raw, q)}"
        if where is not None:
            text += f" (in {', '.join(where[q])})" if where.get(q) else " (in no pack)"
        return text

    shown = ", ".join(one(q) for q in ids[:MAX_IDS_SHOWN])
    extra = len(ids) - MAX_IDS_SHOWN
    return shown + (f", ... (+{extra} more)" if extra > 0 else "")


def build_report(
    raw: RawData,
    packs: list[dict[str, Any]],
    unassigned: dict[str, Any],
    rxp: dict[str, Any],
    faction: str = "horde",
) -> str:
    cfg = get_faction(faction)
    ctx = ShapeContext(raw, cfg)
    ctx.build_quests()
    usage = rxp_usage(rxp)
    rxp_ids = sorted(usage)

    pack_quests: dict[str, dict[int, dict[str, Any]]] = {
        p["id"]: {q["i"]: q for q in p["quests"]} for p in packs
    }
    in_packs: dict[int, list[str]] = defaultdict(list)
    for pid, quests in pack_quests.items():
        for qid in quests:
            in_packs[qid].append(pid)
    unassigned_ids = {q for band in unassigned.values() for ids in band.values() for q in ids}
    placed = set(in_packs)

    out: list[str] = []
    w = out.append
    w("# RXPGuides cross-check (generated)")
    w("")
    w("Generated by `python -m pipeline rxp-crosscheck`. Do not edit by hand.")
    w("")
    w("Source: RXPGuides Forever Horde guides (ids and step order only; no text, coordinates or")
    w("notes were read). Licence of the source: CC BY-NC-SA 4.0 (its `LICENSE`), so only facts")
    w("(quest ids) and counts appear here. Names come from our own DB.")
    w("")
    sources = ", ".join(
        f"{s['file'].split('/')[-1]} (sha256 {s['sha256'][:12]})" for s in rxp["sources"]
    )
    w(f"Guides read: {sources}.")
    w("")
    w("RXP's Forever Horde guides stop at about level 22 (Durotar 1-12, Undead 1-14, Mulgore 1-12,")
    w("Barrens 12-22, plus a Mage guide 12-21). Nothing above that can be cross-checked.")
    w("")
    by_branch: dict[str, set[int]] = defaultdict(set)
    for qid, row in usage.items():
        for b in row["branches"]:
            by_branch[b].add(qid)
    w("## Summary")
    w("")
    w(f"- Distinct quest ids RXP uses: {len(rxp_ids)} "
      f"({', '.join(f'{b}: {len(by_branch[b])}' for b in sorted(by_branch))}).")
    covered = [q for q in rxp_ids if q in placed]
    w(f"- Found in at least one of our packs: {len(covered)} of {len(rxp_ids)}.")
    w(f"- Not in any pack: {len(rxp_ids) - len(covered)} (see the reason table).")
    w("")

    # --- not in any pack, by reason
    missing = [q for q in rxp_ids if q not in placed]
    reasons: dict[str, list[int]] = defaultdict(list)
    for qid in missing:
        reasons[_reason(ctx, raw, qid, unassigned_ids)].append(qid)
    w("## RXP quests that are in none of our packs")
    w("")
    if not missing:
        w("None.")
        w("")
    for reason in sorted(reasons):
        ids = reasons[reason]
        w(f"### {reason} ({len(ids)})")
        w("")
        w(_ids(raw, ids))
        w("")

    # --- per pack coverage
    w("## Per pack")
    w("")
    w("`RXP in pack` counts RXP quest ids found in the pack. `RXP in window, missing from band`")
    w("counts RXP quests (from guides of this pack's branch; every guide for shared packs) whose")
    w(f"level lies in the band window [lo-{WINDOW}, hi+{WINDOW}] and that are in no pack of")
    w("the same band.")
    w("")
    w("| pack | quests | RXP in pack | RXP in window, missing from band |")
    w("|---|---:|---:|---:|")
    band_missing: dict[tuple[int, int], dict[str, list[int]]] = {}
    for pack in packs:
        lo, hi = pack["band"]
        branch = pack["branch"]
        band_ids = {q for p in packs if p["band"] == pack["band"] for q in pack_quests[p["id"]]}
        wanted = set(usage) if branch == "horde" else by_branch.get(branch, set())
        miss = sorted(
            q for q in wanted
            if q in raw.quests and q not in band_ids and q in ctx.quests
            and lo - WINDOW <= ctx.quests[q].level <= hi + WINDOW
        )
        band_missing.setdefault((lo, hi), {})[pack["id"]] = miss
        have = sum(1 for q in pack_quests[pack["id"]] if q in usage)
        w(f"| {pack['id']} | {len(pack_quests[pack['id']])} | {have} | {len(miss)} |")
    w("")
    for (lo, hi), per in sorted(band_missing.items()):
        any_missing = {pid: ids for pid, ids in per.items() if ids}
        if not any_missing:
            continue
        w(f"### Band {lo}-{hi}: RXP quests in the level window but in no pack of the band")
        w("")
        for pid in sorted(any_missing):
            w(f"- `{pid}`: {_ids(raw, any_missing[pid], in_packs)}")
        w("")

    # --- flags
    w("## Quests we flag elite / group / dungeon that RXP does as normal steps")
    w("")
    flagged: dict[str, list[int]] = defaultdict(list)
    for pack in packs:
        for quest in pack["quests"]:
            if quest["i"] in usage:
                for flag in RISKY_FLAGS:
                    if flag in quest.get("fl", []) and quest["i"] not in flagged[flag]:
                        flagged[flag].append(quest["i"])
    for flag in RISKY_FLAGS:
        ids = sorted(flagged[flag])
        w(f"- `{flag}` ({len(ids)}): {_ids(raw, ids) if ids else 'none'}")
    w("")
    w("## Chain heads and breadcrumbs RXP uses that we flagged as droppable")
    w("")
    for flag in DROPPABLE_FLAGS:
        ids = sorted(
            {
                q["i"]
                for p in packs
                for q in p["quests"]
                if q["i"] in usage and flag in q.get("fl", [])
            }
        )
        w(f"- `{flag}` ({len(ids)}): {_ids(raw, ids) if ids else 'none'}")
    w("")

    # --- findings (data-driven)
    w("## Shaping findings")
    w("")
    findings = _findings(reasons, raw, ctx, usage, packs)
    for line in findings or ["No systematic gap found."]:
        w(line)
    w("")
    return "\n".join(out)


def _item_started(raw: RawData, ctx: ShapeContext) -> tuple[int, int]:
    """(Horde-available quests dropped for having no starter, of which an item starts them)."""
    by_item = {int(i["startQuest"]) for i in raw.items.values() if i.get("startQuest")}
    dropped = [
        qid for qid, q in sorted(raw.quests.items())
        if qid not in ctx.quests and not q.get("placeholder")
        and race_available(int(q.get("requiredRaces", 0)), ctx.cfg)
        and not any(refs_ for refs_ in (q.get("startedBy") or {}).values())
    ]
    return len(dropped), sum(1 for qid in dropped if qid in by_item or q_has_source(raw, qid))


def q_has_source(raw: RawData, qid: int) -> bool:
    return bool(raw.quests[qid].get("sourceItemId"))


def _findings(
    reasons: dict[str, list[int]],
    raw: RawData,
    ctx: ShapeContext,
    usage: dict[int, dict[str, Any]],
    packs: list[dict[str, Any]],
) -> list[str]:
    lines: list[str] = []
    other = reasons.get("not available to Horde (race/faction bits)", [])
    if other:
        masks = Counter(int(raw.quests[q].get("requiredRaces", 0)) for q in other)
        mask_text = ", ".join(f"{m:#x} x{c}" for m, c in sorted(masks.items()))
        lines.append(
            f"- {len(other)} RXP Horde quests fail our race/faction filter "
            f"(requiredRaces masks: {mask_text}). "
            "If the mask has the Horde bit the filter is wrong; otherwise it is a DB or RXP issue."
        )
    nostart = reasons.get("no usable starter", [])
    if nostart:
        item_started = [
            q for q in nostart
            if raw.quests[q].get("sourceItemId")
            or any(int(i.get("startQuest") or 0) == q for i in raw.items.values())
        ]
        lines.append(
            f"- {len(nostart)} RXP quests are dropped by us for having no starter. "
            f"{len(item_started)} of them are started by an item (`items.startQuest` or "
            "`sourceItemId`), which the DB does not copy into the quest's `startedBy`."
        )
        total, by_item = _item_started(raw, ctx)
        lines.append(
            f"  - Across the whole DB, {total} Horde-available quests are dropped for having "
            f"no starter; {by_item} of those have an item that starts them. Proposed fix "
            "(not applied, it adds quests to every band and re-splits packs): in "
            "`ShapeContext.build_quests`, build `items.startQuest` -> item starters (kind `i`) "
            "and use them when `startedBy` is empty."
        )
    unplaced = [r for r in reasons if r.startswith("kept by filters")]
    count = sum(len(reasons[r]) for r in unplaced)
    if count:
        lines.append(
            f"- {count} RXP quests pass every filter but land in no pack (band window or branch "
            "rules). Check their levels against the 5-level bands."
        )
    zeph_ids = {q["i"] for p in packs if p["branch"] == "zephras" for q in p["quests"]}
    lines.append(
        f"- {len(zeph_ids & set(usage))} of the {len(zeph_ids)} distinct Zephra's Isle pack "
        "quests appear in RXP's Forever Horde guides (it is a Forever-only start zone)."
    )
    return lines


def run_crosscheck(
    raw_dir: Path = Path("data/raw"),
    data_dir: Path = Path("data"),
    faction: str = "horde",
    out: Path = Path("docs/reports/rxp_crosscheck.md"),
) -> Path:
    raw = load_raw(raw_dir)
    rxp = json.loads((raw_dir / "game" / "rxp_quest_ids.json").read_text(encoding="utf-8"))
    packs = load_packs(data_dir / faction / "bands")
    unassigned = json.loads((data_dir / faction / "unassigned.json").read_text(encoding="utf-8"))
    text = build_report(raw, packs, unassigned, rxp, faction)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    return out
