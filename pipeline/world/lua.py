"""Deterministic Lua writer for the world model.

Every table is written with sorted keys (integer keys first, numerically, then string keys
alphabetically), lists keep their order (the builder sorts them), and there are no timestamps.
Zone files register a builder function, so the add-on only creates a zone's tables when the zone
is first used (``K.WorldDB.Zone(uiMap)``); the index and travel graph register plain tables.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from pipeline.routes.compile_routes import lua_num, lua_str
from pipeline.world.build import OUTSIDE, WorldModel

GENERATED_MARK = "-- Generated by `python -m pipeline compile-world`. Do not edit by hand."
FORMAT_VERSION = 1
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_RESERVED = frozenset(
    "and break do else elseif end false for function if in local nil not or repeat return "
    "then true until while".split()
)
SECTIONS = ("quests", "npcs", "objects", "items", "hubs", "services")


def _key(key: Any) -> str:
    if isinstance(key, bool):
        raise TypeError("boolean table keys are not used")
    if isinstance(key, int):
        return f"[{key}]"
    text = str(key)
    if _IDENT.match(text) and text not in _RESERVED:
        return text
    return f"[{lua_str(text)}]"


def _sort_key(key: Any) -> tuple[int, Any]:
    return (0, key) if isinstance(key, int) else (1, str(key))


def lua_value(value: Any) -> str:
    """One Lua expression for a JSON-like value."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return lua_num(value)
    if isinstance(value, str):
        return lua_str(value)
    if isinstance(value, (list, tuple)):
        return "{" + ", ".join(lua_value(v) for v in value) + "}"
    if isinstance(value, dict):
        items = sorted(value.items(), key=lambda kv: _sort_key(kv[0]))
        return "{" + ", ".join(f"{_key(k)} = {lua_value(v)}" for k, v in items) + "}"
    raise TypeError(f"cannot write {type(value).__name__} to Lua")


def _section(name: str, rows: Any, indent: str) -> list[str]:
    """``name = { [id] = {...}, ... }`` with one row per line."""
    lines = [f"{indent}{name} = {{"]
    if isinstance(rows, dict):
        for key in sorted(rows, key=_sort_key):
            lines.append(f"{indent}    {_key(key)} = {lua_value(rows[key])},")
    else:
        for row in rows:
            lines.append(f"{indent}    {lua_value(row)},")
    lines.append(f"{indent}}},")
    return lines


def _header(model: WorldModel, title: str) -> list[str]:
    db = model.db
    return [
        GENERATED_MARK,
        f"-- QuestieDB {db.get('questieDbVersion', '?')} (commit {db.get('buildCommit', '?')})",
        f"-- {title}",
        "-- Keys: docs/PRD.md s6.8 (world data model).",
        "local _, K = ...",
    ]


def zone_lua(model: WorldModel, ui_map: int) -> str:
    table = model.tables[ui_map]
    if ui_map == OUTSIDE:
        title = "NPCs and objects referenced by compiled quests whose home zone is not compiled."
        meta: dict[str, Any] = {"id": OUTSIDE, "key": "outside", "name": "Outside"}
    else:
        meta = table["meta"]
        title = (
            f"{meta['name']} (uiMapID {ui_map}): {len(table['quests'])} quests, "
            f"{len(table['npcs'])} NPCs, {len(table['objects'])} objects, "
            f"{len(table['hubs'])} hubs."
        )
    lines = _header(model, title)
    lines.append(f"K.WorldDB.RegisterZone({ui_map}, function()")
    lines.append("    return {")
    for key in sorted(meta):
        lines.append(f"        {_key(key)} = {lua_value(meta[key])},")
    lines.append(f"        v = {FORMAT_VERSION},")
    for name in SECTIONS:
        if name in table:
            lines.extend(_section(name, table[name], "        "))
    lines.append("    }")
    lines.append("end)")
    return "\n".join(lines) + "\n"


def index_lua(model: WorldModel) -> str:
    lines = _header(model, "Where each quest, NPC and object lives; zone level ranges; groups.")
    lines.append("K.WorldDB.RegisterIndex({")
    lines.append(f"    faction = {lua_str(model.config.faction)},")
    lines.append(f"    v = {FORMAT_VERSION},")
    for name in ("zones", "quests", "npcs", "objects", "ex", "eq", "dungeons"):
        lines.extend(_section(name, model.index[name], "    "))
    lines.append(f"    xpl = {lua_value(model.index['xpl'])},")
    lines.append("})")
    return "\n".join(lines) + "\n"


def travel_lua(model: WorldModel) -> str:
    lines = _header(model, "Travel graph: flight nodes, boat and zeppelin docks, adjacency.")
    lines.append("K.WorldDB.RegisterTravel({")
    lines.append(f"    cost = {lua_value(model.travel['cost'])},")
    for name in ("nodes", "links", "adj"):
        lines.extend(_section(name, model.travel[name], "    "))
    lines.append("})")
    return "\n".join(lines) + "\n"


def world_files(model: WorldModel, out_dir: Path) -> dict[Path, str]:
    """Every generated file, keyed by path."""
    files: dict[Path, str] = {}
    for zone in model.zones:
        files[out_dir / f"{zone.file_stem}.lua"] = zone_lua(model, zone.ui_map)
    files[out_dir / "Outside.lua"] = zone_lua(model, OUTSIDE)
    files[out_dir / "Index.lua"] = index_lua(model)
    files[out_dir / "Travel.lua"] = travel_lua(model)
    return files


def toc_lines(model: WorldModel) -> list[str]:
    """TOC entries in load order: index, travel, then zone files (uiMap order), Outside last."""
    names = ["Index", "Travel", *(z.file_stem for z in model.zones), "Outside"]
    return [f"World\\{name}.lua" for name in names]


def write_files(files: dict[Path, str], out_dir: Path) -> list[Path]:
    """Write ``files``; delete stale generated files in ``out_dir``. Returns removed paths."""
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    removed: list[Path] = []
    for path in sorted(out_dir.glob("*.lua")):
        if path not in files and path.read_text(encoding="utf-8").startswith(GENERATED_MARK):
            path.unlink()
            removed.append(path)
    return removed


def sync_toc(toc_path: Path, model: WorldModel) -> bool:
    """Rewrite the world block of the add-on .toc. Returns True when the file changed.

    The block is ``WorldDB.lua`` followed by :func:`toc_lines`, placed right before the first
    ``Routes\`` line (or ``Core.lua`` when there are no routes). Any older world lines are dropped.
    """
    text = toc_path.read_text(encoding="utf-8")
    lines = [ln for ln in text.splitlines() if not _is_world_line(ln)]
    block = ["WorldDB.lua", *toc_lines(model)]
    at = next(
        (i for i, ln in enumerate(lines) if ln.startswith("Routes\\") or ln == "Core.lua"),
        len(lines),
    )
    new_text = "\n".join(lines[:at] + block + lines[at:]) + "\n"
    if new_text == text:
        return False
    toc_path.write_text(new_text, encoding="utf-8", newline="\n")
    return True


def _is_world_line(line: str) -> bool:
    stripped = line.strip()
    return stripped == "WorldDB.lua" or stripped.startswith("World\\")
