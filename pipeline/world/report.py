"""Coverage and gaps report for the compiled world (``docs/reports/world_coverage.md``).

Deterministic: no timestamps, every list sorted. Written by ``compile-world``.
"""

from __future__ import annotations

from collections import Counter
from typing import Any

from pipeline.world.build import WorldModel
from pipeline.world.services import CLASS_ROLES, PLAIN_ROLES, PROF_ROLES
from pipeline.world.validate import GraphReport


def _pct(part: int, whole: int) -> str:
    return f"{part}/{whole} ({round(100 * part / whole) if whole else 0}%)"


def coverage_report(model: WorldModel, report: GraphReport) -> str:
    graph = model.graph
    db = model.db
    lines = [
        "# World data: coverage and gaps",
        "",
        "Generated by `python -m pipeline compile-world` (phase 19). Do not edit by hand.",
        f"QuestieDB {db.get('questieDbVersion', '?')} (commit {db.get('buildCommit', '?')}). "
        f"Faction: {model.config.faction}. Quests with a required level up to "
        f"{model.config.max_required_level}.",
        "",
        "## Zones",
        "",
        "| Zone | uiMapID | Quests | Levels (low, median, high) | NPCs | Objects | Hubs | File |",
        "|---|---|---|---|---|---|---|---|",
    ]
    sizes: dict[str, int] = report.stats.get("bytes", {})
    for zone in model.zones:
        table = model.tables[zone.ui_map]
        lv = table["meta"].get("lv")
        lv_text = f"{lv[0]}, {lv[1]}, {lv[2]}" if lv else "-"
        size = sizes.get(f"{zone.file_stem}.lua")
        size_text = f"{zone.file_stem}.lua, {size // 1024} KB" if size else zone.file_stem
        lines.append(
            f"| {zone.name} | {zone.ui_map} | {len(table['quests'])} | {lv_text} | "
            f"{len(table['npcs'])} | {len(table['objects'])} | {len(table['hubs'])} | {size_text} |"
        )
    other = {
        k: v
        for k, v in sorted(sizes.items())
        if not any(k == f"{z.file_stem}.lua" for z in model.zones)
    }
    if other:
        lines.append("")
        lines.append("Other files: " + ", ".join(f"{k} {v // 1024} KB" for k, v in other.items()))
        lines.append(
            f"Size budget per file: {model.config.size_budget // 1024} KB "
            f"(warning at {model.config.size_warn // 1024} KB)."
        )
    left = model.stats
    lines += [
        "",
        f"Left out in these zones: {left.get('aboveLevel', 0)} quests above the level cap, "
        f"{left.get('events', 0)} holiday, world-event and turn-in quests.",
        "",
        "## Quest data coverage",
        "",
        "| Zone | XP known | Starter placed | Turn-in placed | Objectives placed | "
        "Dungeon/instance refs |",
        "|---|---|---|---|---|---|",
    ]
    for zone in model.zones:
        quests = model.tables[zone.ui_map]["quests"]
        total = len(quests)
        xp = sum(1 for q in quests.values() if "xp" in q)
        starters = sum(
            1 for qid in quests if any(graph.located(r) for r in graph.quests[qid].starters)
        )
        turnins = sum(1 for qid in quests if graph.finisher_state(qid) == "placed")
        objectives = [o for q in quests.values() for o in q.get("o", []) if o["k"] != "t"]
        placed = sum(1 for o in objectives if "at" in o)
        inst = sum(
            1
            for qid in quests
            if any(
                graph.instanced(r)
                for r in (*graph.quests[qid].starters, *graph.quests[qid].finishers)
            )
        )
        lines.append(
            f"| {zone.name} | {_pct(xp, total)} | {_pct(starters, total)} | "
            f"{_pct(turnins, total)} | {_pct(placed, len(objectives))} | {inst} |"
        )
    lines += [
        "",
        "XP is missing for Forever's own quests (the QuestXP table has no row for them); the zone "
        "level range and the planner use the median XP of the quest level instead (`xpl` in "
        "`Index.lua`).",
        "",
        "## Services per zone",
        "",
        "Faction-friendly NPCs with a spawn in the zone (mail: mailbox objects). Class and "
        "profession trainers are counted together.",
        "",
    ]
    roles = [r for r in PLAIN_ROLES]
    lines.append("| Zone | " + " | ".join(roles) + " | class trainers | profession trainers |")
    lines.append("|---|" + "---|" * (len(roles) + 2))
    for zone in model.zones:
        counts = model.service_index.zone_counts(zone.area) if model.service_index else {}
        cells = [str(counts.get(r, 0)) for r in roles]
        ct = sum(1 for r in CLASS_ROLES if counts.get(r))
        pt = sum(1 for r in PROF_ROLES if counts.get(r))
        lines.append(
            f"| {zone.name} | " + " | ".join(cells) + f" | {ct}/{len(CLASS_ROLES)} classes | "
            f"{pt}/{len(PROF_ROLES)} professions |"
        )
    lines += ["", "### Missing in the zone (nearest zone that has one)", ""]
    for zone in model.zones:
        table = model.tables[zone.ui_map]
        counts = model.service_index.zone_counts(zone.area) if model.service_index else {}
        missing = [r for r in (*PLAIN_ROLES, *CLASS_ROLES) if not counts.get(r)]
        if not missing:
            lines.append(f"- {zone.name}: none")
            continue
        fallback: dict[str, Any] = {}
        for hub in table["hubs"]:
            for role in missing:
                entry = hub["sv"].get(role)
                if entry and "m" in entry:
                    fallback.setdefault(role, entry["m"])
        names = {z.ui_map: z.name for z in model.zones}
        parts = [
            f"{r} ({names.get(fallback[r], f'uiMap {fallback[r]}')})" if r in fallback else r
            for r in missing
        ]
        lines.append(f"- {zone.name}: " + ", ".join(parts))
    lines += _hub_section(model)
    lines += _validator_section(model, report)
    return "\n".join(lines) + "\n"


def _hub_section(model: WorldModel) -> list[str]:
    roles = model.config.required_hub_roles
    lines = [
        "",
        "## Hubs",
        "",
        f"A hub should have {', '.join(roles)} within {model.config.service_nearby:g} map-% "
        "(DYNAMIC_GUIDE_PLAN s7); a hub that does not lists the role in `gap`. Hubs are "
        "clusters of quest givers and turn-ins, so many are small camps.",
        "",
        "| Zone | Hubs | With all nearby | Gaps by role |",
        "|---|---|---|---|",
    ]
    for zone in model.zones:
        hubs = model.tables[zone.ui_map]["hubs"]
        complete = sum(1 for h in hubs if not h.get("gap"))
        gaps: Counter[str] = Counter(r for h in hubs for r in h.get("gap", []))
        gap_text = ", ".join(f"{r} {gaps[r]}" for r in sorted(gaps)) or "none"
        lines.append(f"| {zone.name} | {len(hubs)} | {complete} | {gap_text} |")
    lines += ["", "### Hubs with three or more quests and a gap", ""]
    for zone in model.zones:
        for hub in model.tables[zone.ui_map]["hubs"]:
            if len(hub.get("qs", [])) >= 3 and hub.get("gap"):
                near = []
                for role in hub["gap"]:
                    entry = hub["sv"].get(role)
                    if entry and "d" in entry:
                        near.append(f"{role} at {entry['d']:g}")
                    elif entry and "m" in entry:
                        near.append(f"{role} in uiMap {entry['m']}")
                    else:
                        near.append(f"{role}: none nearby")
                lines.append(
                    f"- {zone.name}, {hub['name']} (`{hub['id']}`, {len(hub['qs'])} quests): "
                    + "; ".join(near)
                )
    return lines


def _validator_section(model: WorldModel, report: GraphReport) -> list[str]:
    counts: Counter[str] = Counter()
    for issue in report.issues:
        counts[f"{issue.severity} {issue.code}" + (" (reviewed)" if issue.reviewed else "")] += 1
    corrections = model.corrections
    lines = [
        "",
        "## Graph validator",
        "",
        f"{len(report.errors)} error(s), {len(report.warnings)} warning(s), "
        f"{len(report.infos)} info(s).",
        "",
    ]
    lines += [f"- {key}: {value}" for key, value in sorted(counts.items())]
    lines += [
        "",
        "## Curated corrections",
        "",
        f"`data/{model.config.faction}/world/corrections.json`: "
        f"{len(corrections.equivalents)} equivalent groups, "
        f"{len(corrections.not_duplicates)} not-duplicate groups, "
        f"{len(corrections.npc_positions)} NPC positions, "
        f"{len(corrections.quests)} quest statuses.",
    ]
    return lines
