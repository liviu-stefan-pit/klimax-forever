"""Compile validated route JSON into Lua tables for the add-on (PRD 6.7).

Output is deterministic: step order is the route's own order, every other collection is sorted,
and there are no timestamps. Files carry a header with the QuestieDB version and commit.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from pipeline.routes.ui_maps import ui_map_for
from pipeline.routes.validate_route import Report, RouteValidator, load_route_dir, validate_set
from pipeline.routes.world import World

GENERATED_MARK = "-- Generated by `python -m pipeline compile`. Do not edit by hand."

# step type -> compact letter (PRD 6.7)
TYPE_LETTERS: dict[str, str] = {
    "ACCEPT": "A",
    "COMPLETE": "C",
    "TURNIN": "T",
    "TRAVEL": "V",
    "FLY": "F",
    "FP_DISCOVER": "D",
    "HEARTH_BIND": "H",
    "HEARTH_USE": "U",
    "BUY": "B",
    "TRAINER": "R",
    "VENDOR_REPAIR": "P",
    "NOTE": "N",
}
TAG_LETTERS = {"main": "m", "optional": "o", "optional-elite": "e"}


class CompileRefused(Exception):
    """Raised when a route fails validation; carries the reports that explain why."""

    def __init__(self, reports: list[Report]) -> None:
        self.reports = reports
        failed = [r.route_id for r in reports if not r.ok]
        super().__init__(f"validation failed for: {', '.join(failed)}")


class CompileError(Exception):
    """A problem found while compiling (for example a zone with no uiMapID)."""


@dataclass
class CompileResult:
    files: dict[Path, str] = field(default_factory=dict)
    reports: list[Report] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)


# ---- Lua writers ---------------------------------------------------------------------------


def lua_str(value: str) -> str:
    out = ['"']
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append(f"\\{ord(ch):03d}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def lua_num(value: float | int) -> str:
    """Integers stay integers; floats print with 1-2 decimals (52.0, 31.25)."""
    if isinstance(value, int):
        return str(value)
    text = f"{value:.2f}".rstrip("0")
    return text + "0" if text.endswith(".") else text


def lua_list(values: list[Any]) -> str:
    return "{" + ", ".join(lua_str(v) if isinstance(v, str) else lua_num(v) for v in values) + "}"


def step_key(route_id: str, step: dict[str, Any], used: dict[str, int]) -> str:
    """Stable key for saved progress (PRD 7.13): ``routeId:type:quest:objIndex`` or a hash."""
    letter = TYPE_LETTERS[step["type"]]
    if "quest" in step:
        base = f"{route_id}:{letter}:{step['quest']}:{step.get('objectiveIndex', 0)}"
    else:
        material = "|".join(
            str(step.get(name, ""))
            for name in ("zone", "x", "y", "npc", "to", "note", "classes", "races")
        )
        digest = hashlib.sha1(f"{step['type']}|{material}".encode()).hexdigest()[:8]
        base = f"{route_id}:{letter}:h{digest}"
    used[base] = used.get(base, 0) + 1
    return base if used[base] == 1 else f"{base}:{used[base]}"


def db_header(db: dict[str, str]) -> str:
    return f"-- QuestieDB {db.get('questieDbVersion', '?')} (commit {db.get('buildCommit', '?')})"


def prerequisite_ids(quest_id: int, world: World) -> dict[str, list[int]]:
    """Return ``{"all": [...], "any": [...]}`` for a quest, as sorted positive ids."""
    row = world.quests.get(quest_id, {})
    own = {quest_id, *(int(x) for x in row.get("exclusiveTo", []) or [])}

    def clean(ids: list[Any] | None) -> list[int]:
        return sorted({int(x) for x in ids or [] if int(x) > 0 and int(x) not in own})

    return {"all": clean(row.get("preQuestGroup")), "any": clean(row.get("preQuestSingle"))}


def compile_step(
    route: dict[str, Any], step: dict[str, Any], world: World, ui_maps: dict[str, int],
    used: dict[str, int], expected: float | None = None,
) -> str:
    parts = [f"k={lua_str(step_key(route['id'], step, used))}", f"t={lua_str(TYPE_LETTERS[step['type']])}"]
    if "quest" in step:
        parts.append(f"q={step['quest']}")
        title = step.get("title") or world.quest_name(step["quest"])
        parts.append(f"n={lua_str(title)}")
        parts.append(f"g={lua_str(TAG_LETTERS[step['tag']])}")
        quest_level = world.quests.get(step["quest"], {}).get("questLevel")
        if isinstance(quest_level, int) and quest_level > 0:
            parts.append(f"ql={quest_level}")
    if expected is not None:
        # Expected player level at this step (PRD 7.9): used by the level sync to decide on archives.
        parts.append(f"el={int(expected)}")
    if "reward" in step:
        # Key reward (PRD 7.9 gear exception): the route names an item worth a detour.
        parts.append("kr=true")
    if "zone" in step:
        parts.append(f"z={ui_maps[step['zone']]}")
    if "x" in step:
        parts.append(f"x={lua_num(step['x'])}")
        parts.append(f"y={lua_num(step['y'])}")
    if "npc" in step:
        parts.append(f"npc={step['npc']}")
    if "to" in step:
        parts.append(f"to={lua_str(step['to'])}")
    if "note" in step:
        parts.append(f"note={lua_str(step['note'])}")
    if "classes" in step:
        parts.append(f"cl={lua_list(sorted(step['classes']))}")
    if "races" in step:
        parts.append(f"ra={lua_list(sorted(step['races']))}")
    if step["type"] == "ACCEPT" and "quest" in step:
        # Prerequisites for the engine's skip cascade (phase 06). Self and exclusive ids are not
        # real prerequisites, and negative ids are not handled yet (see PROGRESS.md), so drop them.
        prereqs = prerequisite_ids(step["quest"], world)
        if prereqs["all"]:
            parts.append(f"pa={lua_list(prereqs['all'])}")
        if prereqs["any"]:
            parts.append(f"po={lua_list(prereqs['any'])}")
    if "minLevel" in step:
        parts.append(f"ml={step['minLevel']}")
    if step.get("bagCheck"):
        parts.append("bag=true")
    if "reward" in step:
        reward = step["reward"]
        parts.append(f"rw={{item={reward['preferItem']}, why={lua_str(reward['why'])}}}")
    if "revisitAt" in step:
        parts.append(f"rv={step['revisitAt']}")
    if "objectiveIndex" in step:
        parts.append(f"oi={step['objectiveIndex']}")
    return "{" + ", ".join(parts) + "}"


def place_lua(place: dict[str, Any], ui_maps: dict[str, int]) -> str:
    parts = [
        f"z={ui_maps[place['zone']]}",
        f"x={lua_num(place['x'])}",
        f"y={lua_num(place['y'])}",
        f"lv={place['level']}",
    ]
    if place.get("hub"):
        parts.append(f"hub={lua_str(place['hub'])}")
    return "{" + ", ".join(parts) + "}"


def compile_route(route: dict[str, Any], world: World, ui_maps: dict[str, int]) -> str:
    lines = [
        GENERATED_MARK,
        db_header(route["db"]),
        "Klimax_RegisterRoute({",
        f"  id = {lua_str(route['id'])}, faction = {lua_str(route['faction'])}, "
        f"branch = {lua_str(route['branch'])}, lo = {route['band'][0]}, hi = {route['band'][1]},",
    ]
    if route.get("next"):
        lines.append(f"  next = {lua_str(route['next'])},")
    if route.get("sample"):
        lines.append("  sample = true,")
    lines.append(f"  entry = {place_lua(route['entry'], ui_maps)},")
    lines.append(f"  exit = {place_lua(route['exitPoint'], ui_maps)},")
    lines.append("  steps = {")
    used: dict[str, int] = {}
    levels, _info = RouteValidator(world)._expected_levels(route)
    for step, level in zip(route["steps"], levels):
        lines.append(f"    {compile_step(route, step, world, ui_maps, used, level)},")
    lines.append("  },")
    lines.append("})")
    return "\n".join(lines) + "\n"


def compile_index(routes: dict[str, dict[str, Any]], world: World) -> str:
    lines = [GENERATED_MARK, _manifest_header(world), "Klimax_RegisterIndex({", "  routes = {"]
    quest_routes: dict[int, set[str]] = {}
    for rid in sorted(routes):
        route = routes[rid]
        nxt = f", next={lua_str(route['next'])}" if route.get("next") else ""
        lines.append(
            f"    [{lua_str(rid)}] = {{branch={lua_str(route['branch'])}, lo={route['band'][0]}, "
            f"hi={route['band'][1]}{nxt}, steps={len(route['steps'])}}},"
        )
        for step in route["steps"]:
            if "quest" in step:
                quest_routes.setdefault(step["quest"], set()).add(rid)
    lines.append("  },")
    first: dict[str, tuple[int, str]] = {}
    for rid, route in routes.items():
        candidate = (route["band"][0], rid)
        if route["branch"] not in first or candidate < first[route["branch"]]:
            first[route["branch"]] = candidate
    lines.append("  start = {")
    for branch in sorted(first):
        lines.append(f"    {branch} = {lua_str(first[branch][1])},")
    lines.append("  },")
    lines.append("  quests = {")
    for qid in sorted(quest_routes):
        lines.append(f"    [{qid}] = {lua_list(sorted(quest_routes[qid]))},")
    lines.append("  },")
    lines.append("})")
    return "\n".join(lines) + "\n"


def compile_zones(world: World) -> str:
    rows: dict[int, tuple[str, int, int]] = {}
    missing: list[str] = []
    for zone in world.travel.get("zones", []):
        ui_map = ui_map_for(zone["id"], world.area_to_ui_map)
        if not ui_map:
            missing.append(f"{zone['name']} (area {zone['id']})")
            continue
        lo, hi = zone.get("levelRange") or zone.get("levelMinMax") or [1, 60]
        rows[ui_map] = (zone["name"], lo, hi)
    if missing:
        raise CompileError("no uiMapID known for travel.json zones: " + ", ".join(missing))
    lines = [
        GENERATED_MARK,
        _manifest_header(world),
        "-- uiMapID -> {name, minLevel, maxLevel}",
        "Klimax_RegisterZones({",
    ]
    for ui_map in sorted(rows):
        name, lo, hi = rows[ui_map]
        lines.append(f"  [{ui_map}] = {{{lua_str(name)}, {lo}, {hi}}},")
    lines.append("})")
    return "\n".join(lines) + "\n"


def _manifest_header(world: World) -> str:
    return db_header(world.db_stamp())


# ---- driver --------------------------------------------------------------------------------


def resolve_zones(routes: dict[str, dict[str, Any]], world: World) -> dict[str, int]:
    """Zone name -> uiMapID for every zone the routes use. Raises CompileError for gaps."""
    names: set[str] = set()
    for route in routes.values():
        names.add(route["entry"]["zone"])
        names.add(route["exitPoint"]["zone"])
        names.update(step["zone"] for step in route["steps"] if "zone" in step)
    mapping: dict[str, int] = {}
    missing: list[str] = []
    for name in sorted(names):
        area = world.zone_id(name)
        ui_map = ui_map_for(area, world.area_to_ui_map) if area is not None else None
        if ui_map is None:
            missing.append(f"{name} (area {area})")
        else:
            mapping[name] = ui_map
    if missing:
        raise CompileError(
            "no uiMapID known for: " + ", ".join(missing) + ". Add the zone to "
            "pipeline/routes/ui_maps.py (OVERRIDES) once its id is verified."
        )
    return mapping


def compile_faction(
    faction: str,
    routes_dir: Path,
    addon_dir: Path,
    world: World,
    *,
    stitched: bool = False,
) -> CompileResult:
    """Validate every route in ``routes_dir`` and build the Lua files (nothing is written)."""
    routes = load_route_dir(routes_dir)
    if not routes:
        raise CompileError(f"no *.route.json files in {routes_dir}")
    reports = validate_set(routes, world, stitched=stitched)
    result = CompileResult(reports=reports)
    if any(not r.ok for r in reports):
        raise CompileRefused(reports)
    ui_maps = resolve_zones(routes, world)
    out = addon_dir / "Routes" / faction.capitalize()
    for rid, route in routes.items():
        result.files[out / f"{rid}.lua"] = compile_route(route, world, ui_maps)
    result.files[out / "Index.lua"] = compile_index(routes, world)
    result.files[addon_dir / "Data" / "Zones.lua"] = compile_zones(world)
    return result


def write_result(result: CompileResult, faction: str, addon_dir: Path) -> None:
    """Write the files and delete stale generated route files (only ones we generated)."""
    for path, text in result.files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    out = addon_dir / "Routes" / faction.capitalize()
    for path in sorted(out.glob("*.lua")):
        if path in result.files:
            continue
        if path.read_text(encoding="utf-8").startswith(GENERATED_MARK):
            path.unlink()
            result.removed.append(path)


def dumps_report(reports: list[Report]) -> str:
    return json.dumps(
        [{"route": r.route_id, "ok": r.ok, "issues": [i.as_dict() for i in r.issues]} for r in reports],
        indent=2,
    )
