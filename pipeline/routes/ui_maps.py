"""Zone (area id) -> ``uiMapID`` for the compiler.

The table is **generated** by ``python -m pipeline extract`` from the Forever zone files in
QuestieDB (``areaIdToUiMapId``, generated base table plus authored override, which includes
every sub-zone resolved to its mapped ancestor) and committed as ``data/ui_maps.json``. Only
the ids that the game data cannot answer live in ``OVERRIDES`` below.
"""

from __future__ import annotations

import json
from pathlib import Path

UI_MAPS_PATH = Path(__file__).resolve().parents[2] / "data" / "ui_maps.json"

# Area ids the game data cannot answer. Empty on purpose: every Horde zone resolves from the
# generated table (Zephra's Isle 16593 -> 2521 and Riverglades 16591 -> 2548 included). Add an
# entry here only with a comment that says why the table is wrong or silent.
OVERRIDES: dict[int, int] = {}

_cache: dict[int, int] | None = None


def load_ui_maps(path: Path = UI_MAPS_PATH) -> dict[int, int]:
    """Read the generated table (``{"areaIdToUiMapId": {area: uiMap}}``). Cached for the default."""
    global _cache
    if path == UI_MAPS_PATH and _cache is not None:
        return _cache
    data = json.loads(path.read_text(encoding="utf-8"))
    table = {int(area): int(ui_map) for area, ui_map in data["areaIdToUiMapId"].items()}
    if path == UI_MAPS_PATH:
        _cache = table
    return table


def build_ui_map_table(zones: dict[str, dict[str, int]], source: dict[str, str]) -> dict[str, object]:
    """The committed table from ``zones.json``. Area 0 and suppressed (0) entries are dropped."""
    area_map = zones.get("areaIdToUiMapId", {})
    table = {str(area): ui_map for area, ui_map in area_map.items() if ui_map}
    return {
        "_note": "Generated by `python -m pipeline extract` from QuestieDB support/Forever/Zones. "
        "Do not edit by hand; use OVERRIDES in pipeline/routes/ui_maps.py.",
        "areaIdToUiMapId": dict(sorted(table.items(), key=lambda kv: int(kv[0]))),
        "source": source,
    }


def ui_map_for(area_id: int, overrides: dict[int, int] | None = None) -> int | None:
    """uiMapID for a zone, or None if unknown.

    Order: ``OVERRIDES`` (hand-checked), a non-zero entry in ``overrides`` (the extract passed in
    by the caller), then the generated table. A 0 entry means "no map" and returns None.
    """
    if area_id in OVERRIDES:
        return OVERRIDES[area_id]
    value = (overrides or {}).get(area_id)
    if value:
        return value
    return load_ui_maps().get(area_id) or None
