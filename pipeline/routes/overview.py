"""Human-readable overview of the stitched routes (``python -m pipeline overview``).

One table per start branch (band -> zones, levels, counts, flight paths, key rewards), followed
by automated review findings: bags, optional-elite revisit levels, trainer cadence, XP, flight
masters not yet discovered, and the reward hints along the path.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path
from typing import Any

from pipeline.routes.validate_route import validate_route
from pipeline.routes.world import World, distance


def _chain(routes: dict[str, dict[str, Any]], root: dict[str, Any], through: int | None) -> list:
    out, seen, current = [], set(), root
    while current and current["id"] not in seen:
        if through is not None and current["band"][0] >= through:
            break
        seen.add(current["id"])
        out.append(current)
        current = routes.get(current.get("next") or "")
    return out


def _item_names(raw: Path) -> dict[int, dict[str, Any]]:
    path = raw / "items.json"
    if not path.exists():
        return {}
    return {int(k): v for k, v in json.loads(path.read_text(encoding="utf-8")).items()}


def _flight_name(world: World, step: dict[str, Any]) -> str:
    zone = world.zone_id(step["zone"])
    best: tuple[float, str] | None = None
    for fm in world.travel.get("flightMasters", []):
        if fm["zone"] != zone:
            continue
        d = distance(step["x"], step["y"], fm["x"], fm["y"])
        if best is None or d < best[0]:
            best = (d, fm.get("nodeName") or fm["name"])
    return best[1] if best and best[0] <= 6 else f"{step['zone']} ({step['x']}, {step['y']})"


def _quest_name(world: World, qid: int) -> str:
    return world.quest_name(qid)


def build_overview(
    routes: dict[str, dict[str, Any]],
    world: World,
    raw: Path,
    data: Path,
    through: int | None = None,
) -> str:
    items = _item_names(raw)
    shared = world.faction.shared_track
    roots = sorted(
        (r for r in routes.values() if r["band"][0] <= 1), key=lambda r: (r["branch"], r["id"])
    )
    lines = [
        "# Klimax route overview",
        "",
        "Generated by `python -m pipeline overview` from `routes/`. Do not edit by hand.",
        f"Scope: levels 1 to {through if through is not None else world.faction.levels[1]}.",
        "",
    ]
    curated_dir = data / world.faction.id / "curated"
    key_rewards: dict[int, set[int]] = {}
    for path in sorted(curated_dir.glob("*.curated.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        key_rewards[payload["id"]] = {
            d["quest"] for d in payload["decisions"] if d.get("keyReward")
        }

    reports = {
        rid: validate_route(route, world, routes) for rid, route in routes.items()
        if through is None or route["band"][0] < through
    }
    discovered_all: set[str] = set()
    hints: list[tuple[str, int, str, str]] = []
    for root in roots:
        chain = _chain(routes, root, through)
        lines += [
            f"## Branch: {root['branch']}",
            "",
            "| Route | Zones | Level in-out | Steps | Main / Opt / Elite | New flight paths | Key rewards |",
            "|---|---|---|---|---|---|---|",
        ]
        for route in chain:
            zones: list[str] = []
            for step in route["steps"]:
                zone = step.get("zone")
                if zone and zone not in zones:
                    zones.append(zone)
            accepted: dict[int, str] = {}
            fps: list[str] = []
            keys: list[str] = []
            for step in route["steps"]:
                if step["type"] == "ACCEPT":
                    accepted[step["quest"]] = step["tag"]
                elif step["type"] == "FP_DISCOVER":
                    name = _flight_name(world, step)
                    fps.append(name)
                    discovered_all.add(name)
                reward = step.get("reward")
                if reward:
                    info = items.get(reward["preferItem"], {})
                    label = info.get("name", f"item {reward['preferItem']}")
                    keys.append(label)
                    hints.append((route["id"], step.get("quest", 0), label, reward["why"]))
            for qid in sorted(key_rewards.get(route["id"], ())):
                if qid in accepted:
                    keys.append(f"quest: {_quest_name(world, qid)}")
            c = Counter(accepted.values())
            lines.append(
                f"| `{route['id']}` | {', '.join(zones[:6])}{'...' if len(zones) > 6 else ''} "
                f"| {route['entry']['level']} - {route['exitPoint']['level']} "
                f"| {len(route['steps'])} | {c['main']} / {c['optional']} / {c['optional-elite']} "
                f"| {', '.join(fps) or '-'} | {', '.join(dict.fromkeys(keys)) or '-'} |"
            )
        exit_ = chain[-1]["exitPoint"]
        lines += ["", f"Path ends at **{exit_.get('hub', exit_['zone'])}**, level {exit_['level']}.", ""]
        if root["branch"] == shared:
            continue

    # ---- review findings -------------------------------------------------------------------
    lines += ["## Review findings", ""]

    lines += ["### XP and trainer cadence per route", "", "| Route | XP vs budget | Worst trainer gap (levels) |", "|---|---|---|"]
    for rid, report in sorted(reports.items()):
        xp = report.stats.get("xp", {})
        ratio = f"{xp.get('ratio', 0) * 100:.0f}%" if xp.get("known", True) else "unknown (no XP rows)"
        gaps = [v["maxGap"] for v in report.stats.get("trainer", {}).values()]
        lines.append(f"| `{rid}` | {ratio} | {max(gaps) if gaps else '-'} |")
    lines.append("")

    # bags
    used: set[int] = set()
    dropped: dict[int, str] = {}
    for route in routes.values():
        for step in route["steps"]:
            if "quest" in step:
                used.add(step["quest"])
        for d in route["dropped"]:
            dropped.setdefault(d["quest"], route["id"])
    bag_rows = []
    bands_dir = data / world.faction.id / "bands"
    seen_bags: set[int] = set()
    for path in sorted(bands_dir.glob("*.json")):
        pack = json.loads(path.read_text(encoding="utf-8"))
        for q in pack["quests"]:
            if any(r.get("bag") for r in q.get("rw", [])) and q["i"] not in seen_bags:
                seen_bags.add(q["i"])
                status = "routed" if q["i"] in used else (
                    f"dropped in {dropped[q['i']]}" if q["i"] in dropped else "not in a written route"
                )
                bag_rows.append((q["i"], q["n"], pack["id"], status))
    lines += ["### Bag quests", "", "| Quest | Name | Pack | Status |", "|---|---|---|---|"]
    lines += [f"| {i} | {n} | `{p}` | {s} |" for i, n, p, s in bag_rows]
    lines.append("")

    # optional-elite without revisitAt
    missing = [
        (r["id"], s["quest"])
        for r in routes.values()
        for s in r["steps"]
        if s["type"] == "ACCEPT" and s["tag"] == "optional-elite" and "revisitAt" not in s
    ]
    lines += ["### Optional-elite steps without `revisitAt`", ""]
    lines += [f"- `{rid}` quest {q} '{_quest_name(world, q)}'" for rid, q in missing] or ["None."]
    lines.append("")

    # flight masters
    pending = sorted(
        {
            fm.get("nodeName") or fm["name"]
            for fm in world.travel.get("flightMasters", [])
            if fm.get("verified")
        }
        - discovered_all
    )
    lines += ["### Verified flight masters not discovered on any path in scope", ""]
    lines += [f"- {name}" for name in pending] or ["None."]
    lines.append("")

    # reward hints (gear curve inputs)
    lines += ["### Reward hints along the paths (gear curve input)", "", "| Route | Quest | Item | Why |", "|---|---|---|---|"]
    for rid, qid, label, why in sorted(set(hints)):
        lines.append(f"| `{rid}` | {qid} | {label} | {why} |")
    if not hints:
        lines.append("| - | - | - | no `reward.preferItem` hints yet |")
    lines += [
        "",
        "Only a few routes carry `reward.preferItem` hints, so a per-archetype gear curve cannot be",
        "built from them yet; the in-game reward advisor (phase 08) decides from the actual items.",
        "",
    ]
    return "\n".join(lines)
