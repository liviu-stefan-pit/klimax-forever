"""Compiler tests: snapshot, determinism, escaping, keys, refusal and stale-file cleanup."""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import pytest

from pipeline.routes.compile_routes import (
    CompileError,
    CompileRefused,
    CompileResult,
    compile_faction,
    lua_num,
    lua_str,
    step_key,
    write_result,
)
from pipeline.tests.routes.helpers import FIXTURES, build_world, load

SNAPSHOTS = FIXTURES / "snapshots"
ROUTE_LUA = Path("Routes") / "Horde" / "horde_durotar_01-05.lua"


def _stage(tmp_path: Path, *names: str) -> tuple[Path, Path]:
    routes_dir = tmp_path / "routes" / "horde"
    routes_dir.mkdir(parents=True)
    for name in names:
        shutil.copy(FIXTURES / f"{name}.route.json", routes_dir / f"{name}.route.json")
    return routes_dir, tmp_path / "Klimax"


def _compile(tmp_path: Path, *names: str) -> tuple[CompileResult, Path]:
    routes_dir, addon = _stage(tmp_path, *names)
    return compile_faction("horde", routes_dir, addon, build_world()), addon


def test_snapshot(tmp_path: Path) -> None:
    result, addon = _compile(tmp_path, "valid_tiny")
    produced = {
        "route.lua": result.files[addon / ROUTE_LUA],
        "Index.lua": result.files[addon / "Routes" / "Horde" / "Index.lua"],
        "Zones.lua": result.files[addon / "Data" / "Zones.lua"],
    }
    for name, text in produced.items():
        expected = (SNAPSHOTS / name).read_text(encoding="utf-8")
        assert text == expected, f"{name} differs from fixtures/snapshots/{name}"


def test_output_is_deterministic(tmp_path: Path) -> None:
    first, _ = _compile(tmp_path / "a", "valid_tiny")
    second, _ = _compile(tmp_path / "b", "valid_tiny")
    texts_a = [text for _, text in sorted(first.files.items())]
    texts_b = [text for _, text in sorted(second.files.items())]
    assert texts_a == texts_b


def test_header_carries_the_db_version() -> None:
    text = (SNAPSHOTS / "route.lua").read_text(encoding="utf-8")
    assert text.splitlines()[1] == "-- QuestieDB 1.0.11 (commit abc123)"


def test_refuses_a_route_that_fails_validation(tmp_path: Path) -> None:
    routes_dir, addon = _stage(tmp_path, "valid_tiny", "err_coordinates_off")
    # err_coordinates_off has the same id as valid_tiny; give it its own so both are compiled
    broken = load("err_coordinates_off")
    broken.update(id="horde_durotar_05-10", band=[5, 10])
    (routes_dir / "err_coordinates_off.route.json").write_text(json.dumps(broken))
    with pytest.raises(CompileRefused) as exc:
        compile_faction("horde", routes_dir, addon, build_world())
    assert any(not r.ok for r in exc.value.reports)
    assert not addon.exists()  # nothing was written


def test_unknown_ui_map_id_stops_the_compile(tmp_path: Path) -> None:
    route = load("valid_tiny")
    world = build_world()
    world.travel["zones"].append(
        {"id": 99999, "name": "Zephra's Isle", "enum": "ZEPHRAS_ISLE", "levelRange": [1, 13]}
    )
    world.__post_init__()
    route["entry"]["zone"] = "Zephra's Isle"
    route["exitPoint"]["zone"] = "Zephra's Isle"
    routes_dir = tmp_path / "routes"
    routes_dir.mkdir()
    (routes_dir / "r.route.json").write_text(json.dumps(route), encoding="utf-8")
    with pytest.raises(CompileError, match="uiMapID"):
        compile_faction("horde", routes_dir, tmp_path / "Klimax", world)


def test_write_removes_only_stale_generated_files(tmp_path: Path) -> None:
    result, addon = _compile(tmp_path, "valid_tiny")
    out = addon / "Routes" / "Horde"
    out.mkdir(parents=True)
    stale = out / "horde_old_01-05.lua"
    stale.write_text("-- Generated by `python -m pipeline compile`. Do not edit by hand.\n")
    handmade = out / "Custom.lua"
    handmade.write_text("-- mine\n")
    write_result(result, "horde", addon)
    assert not stale.exists()
    assert handmade.exists()
    written = (addon / ROUTE_LUA).read_text(encoding="utf-8")
    assert written == result.files[addon / ROUTE_LUA]
    assert "\r" not in written  # always LF


def test_sample_loses_to_a_real_route_with_the_same_id(tmp_path: Path) -> None:
    routes_dir, addon = _stage(tmp_path, "valid_tiny")
    sample = load("valid_tiny")
    sample["sample"] = True
    sample["steps"] = sample["steps"][:2]
    (routes_dir / "_sample.route.json").write_text(json.dumps(sample), encoding="utf-8")
    result = compile_faction("horde", routes_dir, addon, build_world())
    text = result.files[addon / ROUTE_LUA]
    assert "sample = true" not in text
    assert text.count("t=") == 9


def test_lua_string_escaping() -> None:
    assert lua_str('He said "hi"\\\n') == '"He said \\"hi\\"\\\\\\n"'
    assert lua_str("tab\there") == '"tab\\there"'
    assert lua_str("bell\x07") == '"bell\\007"'
    assert lua_str("Zephra’s") == '"Zephra’s"'  # UTF-8 passes through


def test_number_formatting() -> None:
    assert lua_num(52.0) == "52.0"
    assert lua_num(43.29) == "43.29"
    assert lua_num(31.5) == "31.5"
    assert lua_num(7) == "7"


def test_step_keys_are_stable_and_unique() -> None:
    used: dict[str, int] = {}
    accept = {"type": "ACCEPT", "quest": 844, "tag": "main"}
    assert step_key("r", accept, used) == "r:A:844:0"
    complete = {"type": "COMPLETE", "quest": 844, "tag": "main", "objectiveIndex": 2}
    assert step_key("r", complete, used) == "r:C:844:2"
    note = {"type": "NOTE", "note": "Hello", "zone": "Durotar", "x": 1.0, "y": 2.0}
    first = step_key("r", note, used)
    again = step_key("r", note, used)
    assert first.startswith("r:N:h") and again == first + ":2"
    other = {**note, "note": "Different"}
    assert step_key("r", other, {}) != first
    assert step_key("r", note, {}) == first  # same content, same key


def test_index_maps_quests_and_branch_starts(tmp_path: Path) -> None:
    result, addon = _compile(tmp_path, "valid_tiny")
    index = result.files[addon / "Routes" / "Horde" / "Index.lua"]
    assert 'durotar = "horde_durotar_01-05"' in index
    assert '[1] = {"horde_durotar_01-05"}' in index
