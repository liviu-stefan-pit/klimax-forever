"""Phase 08: rares and chests generator (pipeline/smart/gen.py) on a synthetic mini-world."""

from __future__ import annotations

import json
from pathlib import Path

from pipeline.smart import gen

AREA_TO_UI = {"85": 1420, "10": 1413, "99": 1434, "500": 0}


def _write(path: Path, data: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data), encoding="utf-8")


def _world(tmp_path: Path) -> tuple[Path, Path]:
    raw, data = tmp_path / "raw", tmp_path / "data"
    npcs = {
        "10": {
            "name": "Rathorian",
            "rank": 4,
            "minLevel": 15,
            "maxLevel": 15,
            "spawns": {"85": [[50.0, 50.0], [-1, -1]], "10": [[12.0, 12.0]]},
        },
        "11": {
            "name": "Plain Mob",
            "rank": 0,
            "minLevel": 5,
            "maxLevel": 5,
            "spawns": {"85": [[1, 1]]},
        },
        "12": {
            "name": "Too High",
            "rank": 2,
            "minLevel": 70,
            "maxLevel": 70,
            "spawns": {"85": [[2, 2]]},
        },
        "13": {
            "name": "Off Map",
            "rank": 2,
            "minLevel": 20,
            "maxLevel": 20,
            "spawns": {"99": [[3, 3]]},
        },
        "14": {
            "name": "Only Sentinel",
            "rank": 2,
            "minLevel": 20,
            "maxLevel": 20,
            "spawns": {"85": [[-1, -1]]},
        },
    }
    items = {
        "900": {"name": "Long Blade", "class": 2, "itemLevel": 24, "npcDrops": [10]},
        "901": {"name": "Scrap", "class": 15, "itemLevel": 1, "npcDrops": [10]},
        "902": {"name": "Brown Bag", "class": 1, "itemLevel": 5, "npcDrops": [10]},
        "903": {"name": "Cloth Hat", "class": 4, "itemLevel": 3, "npcDrops": [10]},
    }
    objects = {
        "1": {
            "name": "Battered Chest",
            "spawns": {"85": [[10.0, 10.0], [11.0, 11.0], [12.0, 12.0], [13.0, 13.0]]},
        },
        "2": {"name": "Wooden Door", "spawns": {"85": [[1.0, 1.0]]}},
        "3": {"name": "Chester", "spawns": {"85": [[1.0, 1.0]]}},
    }
    travel = {"zones": [{"id": 85, "name": "Tirisfal Glades"}, {"id": 10, "name": "Durotar"}]}
    ui_maps = {"areaIdToUiMapId": AREA_TO_UI}
    _write(raw / "npcs.json", npcs)
    _write(raw / "items.json", items)
    _write(raw / "objects.json", objects)
    _write(data / "horde" / "travel.json", travel)
    _write(data / "ui_maps.json", ui_maps)
    return raw, data


def test_only_horde_zone_rares_are_kept(tmp_path: Path) -> None:
    raw, data = _world(tmp_path)
    area_to_ui = gen.area_to_ui_for_horde(
        json.loads((data / "horde/travel.json").read_text()),
        json.loads((data / "ui_maps.json").read_text()),
    )
    rares = gen.build_rares(
        json.loads((raw / "npcs.json").read_text()),
        json.loads((raw / "items.json").read_text()),
        area_to_ui,
    )
    names = [r.name for r in rares]
    # Plain Mob is not a rare, Too High is over level 60, Off Map is outside the Horde zones,
    # and Only Sentinel has no usable spawn.
    assert names == ["Rathorian"]


def test_rare_spawns_are_capped_and_sentinels_dropped(tmp_path: Path) -> None:
    raw, data = _world(tmp_path)
    area_to_ui = {"85": 1420, "10": 1413}
    rares = gen.build_rares(
        json.loads((raw / "npcs.json").read_text()),
        json.loads((raw / "items.json").read_text()),
        area_to_ui,
    )
    zones = rares[0].zones
    assert zones == {1413: [(12.0, 12.0)], 1420: [(50.0, 50.0)]}
    assert sum(len(v) for v in zones.values()) <= gen.MAX_SPAWNS


def test_notable_drops_skip_junk(tmp_path: Path) -> None:
    raw, data = _world(tmp_path)
    items = json.loads((raw / "items.json").read_text())
    drops = gen._notable_drops(10, items)
    assert drops == ["Long Blade", "Brown Bag"]


def test_only_chest_names_are_kept(tmp_path: Path) -> None:
    raw, data = _world(tmp_path)
    area_to_ui = {"85": 1420}
    chests = gen.build_chests(json.loads((raw / "objects.json").read_text()), area_to_ui)
    assert [c.name for c in chests] == ["Battered Chest"]
    assert len(chests[0].zones[1420]) == gen.MAX_SPAWNS


def test_output_is_deterministic_and_lua_shaped(tmp_path: Path) -> None:
    raw, data = _world(tmp_path)
    addon = tmp_path / "addon"
    assert gen.write_rares(raw, data, addon) == 1
    assert gen.write_chests(raw, data, addon) == 1
    first = (addon / "Rares.lua").read_text(encoding="utf-8")
    assert gen.write_rares(raw, data, addon) == 1
    assert (addon / "Rares.lua").read_text(encoding="utf-8") == first
    assert first.startswith("-- Generated by `python -m pipeline gen-rares`")
    assert "K.Rares = {" in first
    assert "Long Blade" in first and '"Battered Chest"' not in first
    chests = (addon / "Chests.lua").read_text(encoding="utf-8")
    assert "K.Chests = {" in chests and '"Battered Chest"' in chests
    assert all(len(line) <= 120 for line in first.splitlines() + chests.splitlines())


def test_lua_escapes_quotes_and_backslashes() -> None:
    assert gen._lua_str('say "hi" \\') == '"say \\"hi\\" \\\\"'


def test_real_data_writes_rares_and_chests(tmp_path: Path) -> None:
    raw = Path("data/raw")
    data = Path("data")
    if not (raw / "npcs.json").exists():
        import pytest

        pytest.skip("data/raw is generated by `python -m pipeline extract`")
    addon = tmp_path / "addon"
    assert gen.write_rares(raw, data, addon) > 0
    assert gen.write_chests(raw, data, addon) > 0
