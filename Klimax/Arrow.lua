-- Direction arrow and distance (PRD 7.5).
--
-- The geometry (A.Compute) is pure so the busted specs can check it with stubbed positions.
-- The frame code only reads A.Read() and draws it.
--
-- Angle convention: bearing = atan2(-dx, dy) measured from north (+y), minus the player's facing.
-- A relative angle of 0 means straight ahead and a positive angle means the target is on the left.
-- Compat.GetWorldPos converts Blizzard's world axes (x north, y west) to x east, y north.
local _, K = ...
local L = K.L

local A = {}
K.Arrow = A

A.UPDATE_INTERVAL = 0.1                       -- 10 Hz (PRD 8)
-- Our own white arrowhead (generated by pipeline/media/arrow.py), tinted and rotated in code. The
-- add-on folder must be named Klimax; the texture path has no extension.
A.TEXTURE = "Interface\\AddOns\\Klimax\\Media\\Arrow"
A.SIZE = 44                                  -- fits the 168x86 chip above the distance text
local TWO_PI = 2 * math.pi

-- Wraps an angle into (-pi, pi].
local function wrap(a)
    while a > math.pi do
        a = a - TWO_PI
    end
    while a <= -math.pi do
        a = a + TWO_PI
    end
    return a
end

-- Pure geometry. me and target are {cont = continent map id, x = yards, y = yards}; facing is
-- radians. Returns {kind = "arrow", rot, dist} or {kind = "travel"} when they are on different continents.
function A.Compute(me, target, facing)
    if me.cont ~= target.cont then
        return { kind = "travel" }
    end
    local dx, dy = target.x - me.x, target.y - me.y
    local dist = math.sqrt(dx * dx + dy * dy)
    local rot = wrap(math.atan2(-dx, dy) - facing)
    return { kind = "arrow", rot = rot, dist = dist }
end

-- Player position in world yards: {cont, x, y, map}, or nil when there is no map position
-- (instances and some Classic zones), or when the world conversion is missing.
function A.PlayerWorld()
    local mapID = K.Compat.GetBestMapForPlayer()
    local pos = mapID and K.Compat.GetPlayerMapPosition(mapID)
    if not pos then
        return nil
    end
    local cont, wx, wy = K.Compat.GetWorldPos(mapID, pos.x, pos.y)
    if not cont then
        return nil
    end
    return { cont = cont, x = wx, y = wy, map = mapID }
end

-- The state the arrow should show now: {kind = "hidden" | "arrow" | "travel", rot, dist, zone}.
-- Reads the step the window is showing (K.UI.DisplayIndex), so the arrow follows focus.
function A.Read()
    local hidden = { kind = "hidden" }
    if not A.allowed or K.Option("arrow") == false or not K.UI then
        return hidden
    end
    local E = K.Engine
    local i = K.UI.DisplayIndex(E)
    local s = i and E.steps[i]
    if not s or not s.z or not s.x or not s.y then
        return hidden
    end
    local me = A.PlayerWorld()
    local facing = K.Compat.GetFacing()
    if not me or not facing then
        return hidden
    end
    local cont, tx, ty = K.Compat.GetWorldPos(s.z, s.x / 100, s.y / 100)
    if not cont then
        return hidden
    end
    local res = A.Compute(me, { cont = cont, x = tx, y = ty }, facing)
    local zone = K.zones and K.zones[s.z]
    res.zone = zone and zone[1] or "?"
    res.name = s.n or ""
    return res
end

-- ---- Pointer ---------------------------------------------------------------------------------

A.frame = nil
A.allowed = true          -- set by the main window: false while it is hidden by combat

local NEAR = 20           -- yards; the pointer turns green inside this distance
local T = K.Theme
local W, H = 168, 86

-- Eight-way direction word for a relative angle (0 ahead, positive to the left). Used as the text
-- fallback when the client cannot rotate textures, and in the tooltip. Pure.
local SECTORS = { "AHEAD", "AHEAD_LEFT", "LEFT", "BEHIND_LEFT", "BEHIND", "BEHIND_RIGHT", "RIGHT", "AHEAD_RIGHT" }
function A.Compass(rot)
    local n = math.floor((rot / (math.pi / 4)) + 0.5) % 8
    return SECTORS[n + 1]
end

-- Places the pointer at its saved position, or top-centre of the screen. It is its own frame, so it
-- stays put whether the main window is open or not.
function A.Place()
    local f = A.frame
    if not f then
        return
    end
    f:ClearAllPoints()
    local ui = K.cdb and K.cdb.ui
    local pos = ui and ui.arrowPos
    if pos and pos.point then
        f:SetPoint(pos.point, UIParent, pos.rel, pos.x, pos.y)
    else
        f:SetPoint("TOP", UIParent, "TOP", 0, -70)
    end
    local draggable = not K.Option("locked")
    f:SetMovable(draggable)
    f:EnableMouse(draggable)
    f:SetScale((K.Option("scale") or 1) * (K.Option("arrowScale") or 1))
    if f.label then
        f.label:SetShown(K.Option("arrowLabel") ~= false)
    end
end

-- Builds the pointer frame once: the arrowhead above the distance and the target.
function A.Build()
    if A.frame then
        return
    end
    local f = CreateFrame("Frame", nil, UIParent)
    f:SetSize(W, H)
    f:SetFrameStrata("MEDIUM")
    f:SetClampedToScreen(true)
    f:RegisterForDrag("LeftButton")
    f:SetScript("OnDragStart", function()
        if not K.Option("locked") then
            f:StartMoving()
        end
    end)
    f:SetScript("OnDragStop", function()
        f:StopMovingOrSizing()
        local point, _, rel, x, y = f:GetPoint()
        K.cdb = K.cdb or {}
        K.cdb.ui = K.cdb.ui or {}
        K.cdb.ui.arrowPos = { point = point, rel = rel, x = x, y = y }
    end)
    local tex = f:CreateTexture(nil, "ARTWORK")
    tex:SetSize(A.SIZE, A.SIZE)
    tex:SetPoint("TOP", f, "TOP", 0, -6)
    tex:SetTexture(A.TEXTURE)
    f.tex = tex

    -- text fallback when textures cannot rotate
    f.compass = T.Text(f, 12, T.c.accent, "CENTER", true)
    f.compass:SetPoint("CENTER", tex, "CENTER", 0, 0)
    f.compass:SetWidth(W - 16)

    f.text = T.Text(f, 15, T.c.text, "CENTER", true)
    f.text:SetPoint("TOP", tex, "BOTTOM", 0, -2)
    f.text:SetWidth(W - 16)
    f.label = T.Text(f, 10, T.c.sub, "CENTER")
    f.label:SetPoint("TOP", f.text, "BOTTOM", 0, -1)
    f.label:SetWidth(W - 16)
    -- no backdrop, so the text gets a hard shadow to stay readable on any terrain
    for _, fs in ipairs({ f.compass, f.text, f.label }) do
        fs:SetShadowColor(0, 0, 0, 1)
        fs:SetShadowOffset(1, -1)
    end
    f.rotates = tex.SetRotation ~= nil
    f.arrived = false

    A.frame = f
    A.Place()
    f:Hide()
    return f
end

-- Colours the pointer: accent while walking, green on arrival.
local function tint(f, near)
    local col = near and T.c.good or T.c.accent
    f.tex:SetVertexColor(col[1], col[2], col[3])
    f.text:SetTextColor(near and col[1] or T.c.text[1], near and col[2] or T.c.text[2],
        near and col[3] or T.c.text[3])
end

-- Draws A.Read() on the frame. Called at 10 Hz from the core ticker and after window changes.
function A.Update()
    local f = A.frame
    if not f then
        return
    end
    local r = A.Read()
    if r.kind == "arrow" then
        local near = r.dist < NEAR
        if f.rotates then
            f.tex:SetRotation(r.rot)
            f.tex:Show()
            f.compass:SetText("")
        else
            f.tex:Hide()
            f.compass:SetText(L["ARROW_" .. A.Compass(r.rot)])
        end
        tint(f, near)
        if near and not f.arrived then
            T.Animate("arrow-pulse", 0.4, function(p)
                local base = (K.Option("scale") or 1) * (K.Option("arrowScale") or 1)
                f:SetScale(base * (1 + 0.08 * math.sin(p * math.pi)))
            end)
        end
        f.arrived = near
        f.text:SetText(string.format(L.ARROW_YARDS, math.floor(r.dist + 0.5)))
        f.label:SetText(r.name ~= "" and r.name or r.zone)
        f:Show()
    elseif r.kind == "travel" then
        f.tex:Hide()
        f.compass:SetText("")
        tint(f, false)
        f.arrived = false
        f.text:SetText(string.format(L.ARROW_TRAVEL, r.zone))
        f.label:SetText(r.name)
        f:Show()
    else
        f.arrived = false
        f:Hide()
    end
end

K.Every(A.UPDATE_INTERVAL, function()
    A.Update()
end)
